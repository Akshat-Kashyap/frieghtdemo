function toEnquiry(seed: EnquirySeed): Enquiry {
  const createdAt = daysFromNow(-seed.ageDays)
  return {
    id: seed.id,
    jobId: seed.jobId,
    stage: seed.stage,
    source: seed.source ?? 'WEB_INTAKE',
    customerId: seed.customerId,
    contactPerson: '—',
    contactEmail: '—',
    contactPhone: '—',
    preferredContact: 'EMAIL',
    originId: seed.originId,
    destinationId: seed.destinationId,
    direction: seed.direction,
    mode: seed.mode,
    incoterm: seed.incoterm,
    serviceScope: seed.scope,
    inlandDeliveryRequired: seed.inland ?? false,
    insuranceRequired: seed.insurance ?? false,
    cargo: {
      mode: seed.mode,
      commodity: seed.commodity,
      readyDate: daysFromNow(-seed.ageDays + 6),
      containers: seed.containers,
      packageCount: seed.packages,
      volumeCbm: seed.volumeCbm,
      grossWeightKg: seed.weightKg,
      dangerousGoods: false,
      temperatureControlled: seed.commodity.toLowerCase().includes('frozen') || seed.commodity.toLowerCase().includes('temperature'),
      specialHandling: ['NONE'],
    },
    clearanceCoordinationRequired: seed.clearance ?? false,
    ownerId: seed.owner,
    createdAt,
    updatedAt: hoursFromNow(-Math.max(1, seed.ageDays * 3)),
    estimatedValueInr: seed.valueInr,
    nextAction: seed.nextAction,
    riskLevel: seed.risk,
    quoteIds: [],
    rateRequests:
      seed.stage === 'RATES_REQUESTED'
        ? [
            {
              id: `${seed.id}-RR1`,
              vendorId: 'CARR-MAERSK',
              vendorName: 'Maersk',
              requestedAt: hoursFromNow(-20),
              status: 'REQUESTED',
            },
            {
              id: `${seed.id}-RR2`,
              vendorId: 'CARR-HAPAG',
              vendorName: 'Hapag-Lloyd',
              requestedAt: hoursFromNow(-20),
              respondedAt: hoursFromNow(-4),
              status: 'RECEIVED',
              quotedBuy: 1465,
              currency: 'USD',
              transitDays: 26,
            },
          ]
        : [],
    notes: seed.notes ?? [],
    lostReason: seed.lostReason,
  }
}

